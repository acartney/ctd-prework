# The Three Pillars of Cycling by Cycling Weekly: This script help understand what motivates a cyclist.

miles = int(input("What is your next cycling distance goal in miles? "))
pillar = input("What motivates you most: mastery, autonomy, or belonging? ")

if pillar.lower() == "mastery":
    print("You are driven by progress. Every ride is an opportunity to improve your strength, endurance, and skills.")
elif pillar.lower() == "autonomy":
    print("You ride for yourself. Set your own pace, choose your own roads, and enjoy the freedom of the journey.")
elif pillar.lower() == "belonging":
    print("Cycling is about connection. The best rides are sometimes the ones shared with others.")
else:
    print("Every cyclist has their own motivation. Keep discovering what makes you love the ride.")

print("Your next goal is", miles, "miles, and your strongest pillar is", pillar + ".")

if miles >= 50:
    print("A bigger challenge awaits! Trust your training, embrace the discomfort, and keep pedaling.")
else:
    print("Every mile is progress. Consistency today builds endurance for tomorrow.")